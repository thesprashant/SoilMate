import React from 'react'
import { ShieldAlert, Sprout, AlertTriangle, CheckCircle, Droplets, FlaskConical } from 'lucide-react'
import { localizePlaceName, localizeCropName } from '../utils/geoLocalization'

export default function AdvicePanel({ advisory, latestAssistantMessage, t }) {
  // If we have a saved advisory object
  if (advisory) {
    const alerts = advisory.protective_alerts || []
    const fertSchedule = advisory.fertilizer_schedule || []
    const irrigSchedule = advisory.irrigation_schedule || []

    return (
      <div className="space-y-4">
        {/* Crop Header */}
        <div className="rounded-2xl border border-purple-500/25 bg-purple-950/40 p-4 shadow-glass backdrop-blur-md">
          <div className="flex items-center justify-between">
            <div>
              <span className="text-[10px] font-bold uppercase tracking-wider text-purple-400">
                {t?.adviceTitle || 'Crop Protection Advisory'}
              </span>
              <h2 className="text-xl font-extrabold text-white flex items-center gap-2">
                <Sprout className="text-emerald-400" />
                {localizeCropName(advisory.crop_name, t?._langCode || 'hi')} {advisory.crop_name_local && `(${advisory.crop_name_local})`}
              </h2>
            </div>
            {advisory.season && (
              <span className="px-3 py-1 rounded-full text-xs font-bold uppercase bg-purple-900/60 border border-purple-500/30 text-purple-200">
                {advisory.season} Season
              </span>
            )}
          </div>
          {advisory.location_name && (
            <p className="mt-1 text-xs text-purple-300">
              📍 {t?.historyLocation || 'Location'}: {localizePlaceName(advisory.location_name, t?._langCode || 'hi')}
            </p>
          )}
        </div>

        {/* Full Advisory Body */}
        <div className="rounded-2xl border border-purple-500/20 bg-dark-900/70 p-4 shadow-glass backdrop-blur-md space-y-3">
          <h3 className="text-xs font-bold uppercase tracking-wider text-purple-400">
            {t?.guidanceTitle || 'Agronomic Protective Guidance'}
          </h3>
          <div className="text-xs sm:text-sm text-stone-200 leading-relaxed whitespace-pre-wrap">
            {advisory.full_advisory_text}
          </div>
        </div>


        {/* Dynamic Protective Alerts if available */}
        {alerts.length > 0 && (
          <div className="rounded-2xl border border-amber-500/30 bg-amber-950/30 p-4 shadow-glass space-y-2">
            <h4 className="text-xs font-bold uppercase tracking-wider text-amber-300 flex items-center gap-1.5">
              <AlertTriangle size={15} className="text-amber-400" /> {t?.warningsTitle || 'Protective Warnings'}
            </h4>
            <ul className="space-y-1.5 text-xs text-amber-100">
              {alerts.map((al, idx) => (
                <li key={idx} className="flex items-start gap-2">
                  <span className="w-1.5 h-1.5 rounded-full bg-amber-400 mt-1.5 shrink-0" />
                  <span>{typeof al === 'string' ? al : al.message || JSON.stringify(al)}</span>
                </li>
              ))}
            </ul>
          </div>
        )}
      </div>
    )
  }

  // If no structured advisory, but latest message exists with agronomic reply
  if (latestAssistantMessage && latestAssistantMessage.role === 'assistant') {
    return (
      <div className="space-y-4">
        <div className="rounded-2xl border border-purple-500/25 bg-purple-950/40 p-4 shadow-glass backdrop-blur-md">
          <div className="flex items-center gap-2 text-purple-300 text-xs font-bold uppercase">
            <ShieldAlert size={16} className="text-purple-400" />
            <span>{t?.adviceTitle || 'Latest Advisory Generated by SoilMate'}</span>
          </div>
          <div className="mt-3 text-xs sm:text-sm text-stone-100 leading-relaxed whitespace-pre-wrap">
            {latestAssistantMessage.content}
          </div>
        </div>
      </div>
    )
  }

  // Zero mock empty state
  return (
    <div className="rounded-2xl border border-purple-500/20 bg-dark-900/50 p-8 text-center backdrop-blur-md shadow-glass flex flex-col items-center justify-center space-y-3">
      <div className="p-3 rounded-2xl bg-purple-950/80 border border-purple-500/30 text-purple-400">
        <ShieldAlert size={28} />
      </div>
      <div>
        <h3 className="text-sm font-bold text-white">{t?.noAdviceTitle || 'No Advisory Generated Yet'}</h3>
        <p className="text-xs text-purple-300/70 max-w-sm mt-1 leading-relaxed">
          {t?.noAdviceDesc || 'Ask SoilMate for crop advice to generate customized real agronomic recommendations.'}
        </p>
      </div>
    </div>
  )
}

